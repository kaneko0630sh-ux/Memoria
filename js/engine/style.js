const pickOpt = (g, v) => STYLE_GROUPS[g].options.find(o => o.v === v) || STYLE_GROUPS[g].options[0];

// プロットのスタイル設定から、文体と演出の指示文を組み立てる
export function styleText(style) {
  const lines = [
    '# 文体と演出（厳守）',
    '## 視点・時制・分量',
    ...['pov', 'tense', 'length', 'expr'].map(g => `- ${pickOpt(g, style[g]).rule}`),
    '## 進行',
    ...['difficulty', 'pace'].map(g => `- ${pickOpt(g, style[g]).rule}`),
  ];
  const moods = (style.mood || []).map(v => STYLE_GROUPS.mood.options.find(o => o.v === v)).filter(Boolean);
  if (moods.length) lines.push('## 雰囲気', ...moods.map(o => `- ${o.rule}`));
  const prose = pickOpt('prose', style.prose);
  if (prose.rule) lines.push(`## 文章スタイル「${prose.label}」`, prose.rule);
  lines.push('## 共通',
    '- 感情を説明しすぎない。同じ語彙・言い回し・構文を繰り返さない',
    '- 箇条書き、メタ発言、括弧書きの注釈は書かない（出力形式の見出しは除く）',
    '- {{user}}の台詞・内心・新しい大きな行動を勝手に書かない（{{user}}がすでに示した行動の結果を描くのは可）',
    '- 応答の最後は、{{user}}が返したくなる台詞か、小さな動作・余韻で終える');
  return lines.join('\n');
}

// 表示用の出力形式。アプリがこの形式を解析して吹き出しに分ける
export function formatRules(ctx, style, extra = []) {
  const names = ctx.chars.map(c => c.name);
  const lines = [
    '# 出力形式（厳守・システムが解析して表示します）',
    'ブロックごとに見出し行を置き、その下に本文を書く。',
    '',
    '【ナレーション】',
    '情景・場面の描写（1段落を1行で書く）',
    '',
    '【キャラクター名】',
    '*その人物の動作・表情・内心の段落*',
    'その人物の台詞',
    '*動作の段落*',
    '台詞',
    '',
    `- キャラクター名は ${names.join('、') || '登場人物の名前'} を正確に使う。名前のある脇役が話すときは【その人物の名前】で独立したブロックにする。`,
    '- キャラクターのブロック内では、動作・内心の段落は行頭と行末を必ず * で囲む。台詞は * で囲まず、「」も付けない。',
    '- 1つのブロックに書くのはその人物の動作と台詞だけ。別の人物が話すときはブロックを分ける。',
    '- ナレーションは場面転換・情景・時間の経過・その場全体の空気を描く。台詞は入れない。',
  ];
  const info = [];
  if (style.infoBg === 'on') info.push('📅 日時 / 📍 場所 / 🌤 天気・空気 をそれぞれ1行で');
  if (style.infoChar === 'on') info.push('登場中のキャラクターごとに「名前｜服装｜感情｜{{user}}への印象」を1行で');
  if (info.length) lines.push('- 応答の最後に【情報】ブロックを置き、次を書く: ' + info.join('、') + '。');
  for (const e of extra) if (e) lines.push(e);
  return lines.join('\n');
}
